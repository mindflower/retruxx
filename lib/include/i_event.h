    struct Event;

    struct IEventHandler
    {
        virtual ~IEventHandler() = default /* 0x00 */;
        virtual int HandleEvent(m3d::Event const&) = 0 /* 0x04 */;
    }; /* size: 0x0004 */

    struct Event
    {
        double m_timeStamp = 0.0;
        int m_eventType = 0;
        CStr m_strEv;
        AIParam m_aiParamEv;

        union
        {
            void* m_void[4] = {};
            IEventHandler* m_handle[4];
            unsigned int m_uintEv[4];
            int m_intEv[4];
            unsigned short m_ushortEv[8];
            short m_shortEv[8];
            unsigned char m_byteEv[16];
        }; /* size: 0x0010 */

        CStr Dump() const;
    }; /* size: 0x0048 */
